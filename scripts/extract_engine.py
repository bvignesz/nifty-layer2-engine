class RemoveIO(ast.NodeTransformer):
    def visit_Expr(self, node):
        text = ast.unparse(node)
        if '.to_csv(' in text or text == 'os.sync()' or text.startswith('conn.commit('):
            return None
        return self.generic_visit(node)

    def visit_With(self, node):
        if any('open(' in ast.unparse(item.context_expr) for item in node.items):
            return None
        return self.generic_visit(node)

    def visit_If(self, node):
        if ast.unparse(node.test) == 'is_actionable':
            return None  # Telegram dispatch only
        return self.generic_visit(node)

    def visit_Call(self, node):
        if ast.unparse(node.func) == 'sqlite3.connect':
            node.func = ast.Name(id='_storage_connection', ctx=ast.Load())
        return self.generic_visit(node)


def transformed_tree():
    nb = json.loads((ROOT / 'final.ipynb').read_text())
    tree = ast.parse(''.join(nb['cells'][5]['source']))
    selected = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in FUNCTIONS:
            selected.append(node)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            if any(isinstance(t, ast.Name) and t.id in CONSTANTS for t in targets):
                selected.append(node)
        elif isinstance(node, ast.If) and ast.unparse(node.test) == "ACTIVE_INDEX == 'SENSEX'":
            selected.append(node)
    return ast.fix_missing_locations(RemoveIO().visit(ast.Module(body=selected, type_ignores=[])))


